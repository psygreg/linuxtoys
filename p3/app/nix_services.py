def _snapshot_names():
    """Top-level package attributes in the validated snapshot (mtime-cached)."""
    path = nix_catalog.cached_path()
    if path is None:
        return ()
    key = _path_state(path)
    if key is None:
        return ()
    with _LOCK:
        if (
            _NAME_CACHE["path"] == os.fspath(path)
            and _NAME_CACHE["mtime"] == key
        ):
            return _NAME_CACHE["names"]
    prefix = f"legacyPackages.{nix_catalog.linux_arch()}."
    names = set()
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError, UnicodeError):
        return ()
    if isinstance(payload, dict):
        for key_name in payload:
            if not key_name.startswith(prefix):
                continue
            name = key_name[len(prefix):]
            if _ATTR_RE.fullmatch(name):
                names.add(name)
    result = tuple(sorted(names))
    with _LOCK:
        _NAME_CACHE.update({"path": os.fspath(path), "mtime": key, "names": result})
    return result


def _run_discovery(executable, expression, environment):
    fd, path = tempfile.mkstemp(
        dir=nix_catalog.CACHE_DIR, prefix="services-", suffix=".json"
    )
    try:
        with os.fdopen(fd, "wb") as handle:
            result = subprocess.run(
                [
                    executable,
                    "--extra-experimental-features",
                    "nix-command flakes",
                    "eval",
                    "--impure",
                    "--json",
                    "--expr",
                    expression,
                ],
                stdout=handle,
                stderr=subprocess.PIPE,
                timeout=nix_catalog.SEARCH_TIMEOUT,
                check=False,
                env=environment,
            )
        if result.returncode:
            detail = result.stderr.decode("utf-8", "replace").strip().splitlines()
            raise RuntimeError(
                detail[-1] if detail else "Nix service evaluation failed"
            )
        size = os.path.getsize(path)
        if not 0 < size <= MAX_BYTES:
            raise ValueError("Nix service metadata is empty or too large")
        return path
    except Exception:
        try:
            os.unlink(path)
        except OSError:
            pass
        raise


def _discovery_expression(scope, wanted_path, system, hm_source=None, include_defaults=True):
    # The wanted package attributes live in the JSON file; the expression
    # itself stays constant, so a large nixpkgs revision cannot exceed the
    # command-line argument limit.
    template = (
        _HM_SERVICES_EXPRESSION
        if scope == "home-manager"
        else _NIX_SERVICES_EXPRESSION
    )
    expression = (
        template
        .replace("__HELPERS__", _SERVICE_HELPERS)
        .replace("__SYSTEM__", system)
        .replace("__WANTED__", json.dumps(str(wanted_path)))
        .replace("__DEFAULTS__", "true" if include_defaults else "false")
    )
    if scope == "home-manager":
        expression = expression.replace(
            "__HM_SOURCE__", json.dumps(os.fspath(hm_source or ""))
        )
    return expression


def _discover_scope(scope, wanted_path, executable, system, environment):
    hm_source = home_manager_source() if scope == "home-manager" else None
    if scope == "home-manager" and hm_source is None:
        raise ValueError("The Home Manager module tree could not be located")
    output_path = ""
    try:
        try:
            output_path = _run_discovery(
                executable,
                _discovery_expression(scope, wanted_path, system, hm_source),
                environment,
            )
        except Exception:
            # A single option default that references an unevaluable config
            # value must not hide every service. Retry without defaults; the
            # UI then shows untouched values as unset for that revision.
            output_path = _run_discovery(
                executable,
                _discovery_expression(
                    scope,
                    wanted_path,
                    system,
                    hm_source,
                    include_defaults=False,
                ),
                environment,
            )
        raw = json.loads(Path(output_path).read_text(encoding="utf-8"))
        if not isinstance(raw, dict):
            raise ValueError("Nix service metadata has an unexpected shape")
        if str(raw.get("system") or "") != system:
            raise ValueError(
                "Nix service metadata was generated for another architecture"
            )
        if str(raw.get("scope") or "") != scope:
            raise ValueError("Nix service metadata was generated for another scope")
        return _clean_services({scope: raw.get("services")}).get(scope, {})
    finally:
        if output_path:
            try:
                os.unlink(output_path)
            except OSError:
                pass


def _known_service_names():
    """Service names already in the cache, retained across catalog filtering."""
    names = set()
    for scope_services in cached_services().values():
        names.update(scope_services)
    return names


def discover_services(package_names=None):
    """Evaluate the wanted services and their editable options per level."""
    if not enabled():
        return {}
    if package_names is not None:
        names = tuple(package_names)
    else:
        names = tuple(sorted(set(_snapshot_names()) | _known_service_names()))
    if not names:
        return {}
    executable = nix_catalog.nix_executable()
    system = nix_catalog.linux_arch()
    if not executable or not system:
        return {}
    nix_catalog.CACHE_DIR.mkdir(parents=True, exist_ok=True)
    wanted_fd, wanted_path = tempfile.mkstemp(
        dir=nix_catalog.CACHE_DIR, prefix="services-wanted-", suffix=".json"
    )
    try:
        with os.fdopen(wanted_fd, "w", encoding="utf-8") as handle:
            json.dump(
                [name for name in names if _ATTR_RE.fullmatch(name)],
                handle,
                ensure_ascii=False,
                separators=(",", ":"),
            )
        environment = {
            **os.environ,
            "NIX_CONFIG": (
                (os.environ.get("NIX_CONFIG", "") + "\n")
                if os.environ.get("NIX_CONFIG")
                else ""
            )
            + "extra-experimental-features = nix-command flakes\n",
            "LC_ALL": "C",
        }
        services = {}
        errors = []
        required = set(service_scopes())
        for scope in discovery_scopes():
            try:
                services[scope] = _discover_scope(
                    scope, wanted_path, executable, system, environment
                )
            except Exception as error:
                if scope in required:
                    errors.append(f"{scope}: {error}")
                else:
                    # Filter-only discovery (system services on a Home
                    # Manager-only host) must never break user services.
                    logger.warning(
                        "Nix %s service discovery for compatibility failed: %s",
                        scope,
                        error,
                    )
                    services[scope] = {}
        if errors:
            # Retain the previous complete cache rather than publishing a
            # half-updated service list.
            raise RuntimeError("; ".join(errors))
        return services
    finally:
        try:
            os.unlink(wanted_path)
        except OSError:
            pass


def load_or_refresh(force=False):
    """Refresh the service discovery cache; returns its path or None.

    The previous valid cache is retained on any failure, so a transient Nix or
    network problem never removes the Services tabs.
    """
    global _LAST_FAILURE
    if not enabled():
        return None
    with _LOCK:
        if (
            not force
            and _LAST_FAILURE
            and time.time() - _LAST_FAILURE < FAILURE_BACKOFF
        ):
            return SERVICES_PATH if _path_state(SERVICES_PATH) else None
        if not force and not needs_refresh():
            return SERVICES_PATH if _path_state(SERVICES_PATH) else None
        try:
            services = discover_services()
            if not enabled():
                return None
            payload = {
                "schema": SCHEMA,
                "system": nix_catalog.linux_arch(),
                "hm_source": os.fspath(home_manager_source() or ""),
                "updated": int(time.time()),
                "services": services,
            }
            atomic_write_text(
                os.fspath(SERVICES_PATH),
                json.dumps(
                    payload,
                    ensure_ascii=False,
                    sort_keys=True,
                    separators=(",", ":"),
                )
                + "\n",
                mode=0o600,
                fsync=True,
            )
            with _LOCK:
                _CACHE["path"] = os.fspath(SERVICES_PATH)
                _CACHE["mtime"] = _path_state(SERVICES_PATH)
                _CACHE["services"] = services
            try:
                hidden = unavailable_service_attrs()
                nix_catalog.filter_unavailable_services(hidden)
                # The snapshot filter rewrites the catalog snapshot after the
                # service cache; keep the cache marker newer so it is not
                # treated as stale on the very next readiness check.
                if _path_state(SERVICES_PATH) is not None:
                    os.utime(SERVICES_PATH, None)
                    with _LOCK:
                        _CACHE["mtime"] = _path_state(SERVICES_PATH)
            except Exception as error:
                logger.warning(
                    "Could not update incompatible Nix service packages: %s",
                    error,
                )
            _LAST_FAILURE = 0.0
            return SERVICES_PATH
        except Exception as error:
            _LAST_FAILURE = time.time()
            logger.warning(
                "Nix service refresh failed; retaining cached data: %s", error
            )
            return SERVICES_PATH if _path_state(SERVICES_PATH) else None


