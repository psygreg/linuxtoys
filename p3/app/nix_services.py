def import_name(scope):
    # Home Manager gets the plain name (the user-level module), while the
    # NixOS system module follows the system-* convention used by extensions
    # and flakes.
    return (
        "linuxtoys-system-services.nix"
        if scope == "system"
        else "linuxtoys-services.nix"
    )


def module_path(scope):
    """Path of the generated service module for one scope."""
    return Path(nix_catalog.module_path(scope)).parent / import_name(scope)


def empty_module(scope):
    return render_module(scope, {})


def _read_module_text(path):
    try:
        return Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def read_state(path):
    """Read the service selection recorded in a generated module."""
    for line in _read_module_text(path).splitlines():
        if not line.startswith(STATE_PREFIX):
            continue
        try:
            payload = json.loads(line[len(STATE_PREFIX):])
        except (ValueError, TypeError):
            return {}
        return _clean_state(payload)
    return {}


def _clean_option_value(kind, value, choices=None):
    """Return ``(ok, value)`` for a stored or queued option value."""
    if kind == "bool":
        if isinstance(value, bool):
            return True, value
        if isinstance(value, str) and value.casefold() in ("true", "false"):
            return True, value.casefold() == "true"
        return False, None
    if kind == "enum":
        if isinstance(value, str) and (not choices or value in choices):
            return True, value
        return False, None
    if kind == "int":
        if isinstance(value, bool):
            return False, None
        if isinstance(value, int):
            return True, value
        if isinstance(value, str) and re.fullmatch(r"-?\d+", value.strip()):
            return True, int(value.strip())
        return False, None
    if kind == "float":
        if isinstance(value, bool):
            return False, None
        if isinstance(value, (int, float)):
            number = float(value)
            return (True, number) if math.isfinite(number) else (False, None)
        if isinstance(value, str):
            try:
                number = float(value.strip())
            except ValueError:
                return False, None
            return (True, number) if math.isfinite(number) else (False, None)
        return False, None
    if kind == "text":
        if isinstance(value, str):
            return True, value
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return True, str(value)
        return False, None
    if kind == "list":
        if isinstance(value, list):
            return True, [str(item) for item in value if isinstance(item, (str, int, float))]
        if isinstance(value, str):
            return True, [item.strip() for item in value.splitlines() if item.strip()]
        return False, None
    return False, None


def _infer_kind(value):
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "int"
    if isinstance(value, float):
        return "float"
    if isinstance(value, str):
        return "text"
    if isinstance(value, list):
        return "list"
    return None


def _clean_state(payload):
    if not isinstance(payload, dict):
        return {}
    state = {}
    for name, value in payload.items():
        name = str(name or "").strip()
        if not _ATTR_RE.fullmatch(name):
            continue
        raw_options = value.get("options") if isinstance(value, dict) else None
        if not isinstance(raw_options, dict):
            continue
        options = {}
        for path, option_value in raw_options.items():
            path = str(path or "").strip()
            if not _PATH_RE.fullmatch(path):
                continue
            kind = _infer_kind(option_value)
            if kind is None:
                continue
            ok, cleaned = _clean_option_value(kind, option_value)
            if ok:
                options[path] = cleaned
        state[name] = {"options": options}
    return state


def installed_services(scope=None):
    """Services selected in the generated modules for one or both levels."""
    scopes = [scope] if scope in SERVICE_SCOPES else list(SERVICE_SCOPES)
    names = set()
    for item in scopes:
        names.update(read_state(module_path(item)))
    return names


def installed_service_scopes(name):
    value = str(name or "").strip()
    if not value:
        return []
    return [
        scope for scope in SERVICE_SCOPES if value in installed_services(scope)
    ]


def is_installed(info):
    if not isinstance(info, dict):
        return False
    name = str(info.get("nix_name") or info.get("package-name") or "").strip()
    return bool(name) and bool(installed_service_scopes(name))


