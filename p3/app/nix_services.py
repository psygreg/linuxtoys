# The wanted package attributes are passed through a JSON file (read under
# ``--impure``) so the expression size stays constant. Only services whose
# name is a catalog package attribute are evaluated; this is what makes a
# catalog entry a service entry.
_SERVICE_HELPERS = r"""
  isOption = value: builtins.isAttrs value && (value._type or "") == "option";
  visible = option:
    (option.visible or true) != false
    && !(option.internal or false)
    && !(option.readOnly or false);
  supportedType = type:
    let
      description = type.description or (type.name or "");
    in
    description == "boolean"
    || description == "string"
    || description == "non-empty string"
    || description == "single line string"
    || description == "absolute path"
    || description == "path"
    || description == "path not in the Nix store"
    || description == "list of string"
    || description == "list of non-empty string"
    || description == "list of absolute path"
    || description == "signed integer"
    || description == "unsigned integer"
    || description == "positive integer, meaning >0"
    || description == "16 bit unsigned integer; between 0 and 65535 (both inclusive)"
    || description == "floating point number"
    || lib.hasPrefix "one of " description;
  jsonScalar = value:
    builtins.isBool value
    || builtins.isString value
    || builtins.isPath value
    || builtins.isInt value
    || builtins.isFloat value;
  jsonValue = value:
    if builtins.isString value then builtins.unsafeDiscardStringContext value
    else if builtins.isPath value then
      builtins.unsafeDiscardStringContext (builtins.toString value)
    else if builtins.isBool value || builtins.isInt value || builtins.isFloat value then value
    else if builtins.isList value && lib.all jsonScalar value then
      map
        (item:
          if builtins.isString item then builtins.unsafeDiscardStringContext item
          else if builtins.isPath item then
            builtins.unsafeDiscardStringContext (builtins.toString item)
          else item)
        value
    else null;
  defaultOf = option:
    if option ? default then
      let
        evaluated = builtins.tryEval (
          builtins.fromJSON (builtins.toJSON (jsonValue option.default))
        );
      in
      if evaluated.success then evaluated.value else null
    else null;
  # Defaults are forced only for direct service options. Nested submodule
  # defaults may reference config values that abort module evaluation instead
  # of raising a catchable error; those options stay editable with an empty
  # initial value until the user sets them.
  flatten = prefix: attrs:
    builtins.concatMap
      (name:
        let value = attrs.${name}; in
        if isOption value then
          if visible value && supportedType value.type then
            [{
              path = builtins.concatStringsSep "." (prefix ++ [ name ]);
              type = value.type.description or (value.type.name or "");
              typeName = value.type.name or "";
              description = builtins.substring 0 1000 (value.description or "");
              default = if __DEFAULTS__ && prefix == [ ] then defaultOf value else null;
            }]
          else [ ]
        else if builtins.isAttrs value && !(builtins.hasAttr "_type" value) then
          flatten (prefix ++ [ name ]) value
        else [ ])
      (builtins.filter (name: builtins.substring 0 1 name != "_") (builtins.attrNames attrs));
  serviceRow = name:
    let
      service = services.${name};
      enable = if builtins.isAttrs service then (service.enable or null) else null;
      options = if builtins.isAttrs service then flatten [ ] service else [ ];
    in
    if !(isOption enable) || (enable.type.description or "") != "boolean" then null
    else {
      inherit name;
      description = builtins.substring 0 1000 (enable.description or "");
      options = builtins.filter (item: item.path != "enable") options;
    };
"""

