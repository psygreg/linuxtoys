def _home_manager_binary():
    candidates = [
        shutil.which("home-manager"),
        os.path.expanduser("~/.nix-profile/bin/home-manager"),
        os.path.expanduser("~/.local/state/nix/profile/bin/home-manager"),
    ]
    for candidate in candidates:
        if candidate and os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return os.path.abspath(candidate)
    return None


def home_manager_source():
    """Locate the installed Home Manager module tree, if it can be resolved."""
    override = str(os.environ.get("LINUXTOYS_HOME_MANAGER_SRC") or "").strip()
    if override:
        path = Path(override).expanduser()
        if (path / "modules" / "default.nix").is_file() and (
            path / "modules" / "services"
        ).is_dir():
            return path
        return None
    binary = _home_manager_binary()
    resolved = os.path.realpath(binary) if binary else ""
    with _LOCK:
        if _HM_SOURCE_CACHE["binary"] == resolved:
            return _HM_SOURCE_CACHE["source"]
    source = None
    if resolved:
        nix_store = (
            shutil.which("nix-store")
            or os.path.join(os.path.dirname(nix_catalog.nix_executable() or ""), "nix-store")
        )
        if nix_store and os.path.isfile(nix_store):
            try:
                result = subprocess.run(
                    [nix_store, "-q", "--references", resolved],
                    capture_output=True,
                    text=True,
                    timeout=30,
                    check=False,
                )
                for line in result.stdout.splitlines():
                    candidate = Path(line.strip())
                    if (
                        candidate.is_dir()
                        and (candidate / "modules" / "default.nix").is_file()
                        and (candidate / "modules" / "services").is_dir()
                    ):
                        source = candidate
                        break
            except (OSError, subprocess.SubprocessError):
                source = None
    if source is None:
        executable = nix_catalog.nix_executable()
        if executable:
            try:
                result = subprocess.run(
                    [executable, "flake", "metadata", "home-manager", "--json"],
                    capture_output=True,
                    text=True,
                    timeout=10,
                    check=False,
                )
                if result.returncode == 0:
                    payload = json.loads(result.stdout)
                    candidate = Path(str(payload.get("path") or "")).expanduser()
                    if (
                        candidate.is_dir()
                        and (candidate / "modules" / "default.nix").is_file()
                        and (candidate / "modules" / "services").is_dir()
                    ):
                        source = candidate
            except (OSError, ValueError, TypeError, subprocess.SubprocessError):
                source = None
    with _LOCK:
        _HM_SOURCE_CACHE.update({"binary": resolved, "source": source})
    return source


def service_scopes():
    """Service levels available on this host, user level first."""
    if not nix_catalog.enabled():
        return []
    try:
        catalog_scopes = set(nix_catalog.scopes())
    except Exception:
        return []
    result = []
    if "home-manager" in catalog_scopes and home_manager_source() is not None:
        result.append("home-manager")
    if "system" in catalog_scopes:
        result.append("system")
    return result


def enabled():
    """Whether at least one Nix service level can be managed."""
    return bool(service_scopes())


def scopes():
    """Available scopes for service operations."""
    return service_scopes()


def discovery_scopes():
    """Scopes evaluated for discovery, including system on non-NixOS.

    System service metadata is still needed there to identify packages that
    are incompatible with the host, even though they can never be installed.
    """
    result = list(service_scopes())
    if "system" not in result and nix_catalog.enabled() and nix_catalog.linux_arch():
        result.append("system")
    return result


def _path_state(path):
    try:
        stat = path.stat()
        return (stat.st_size, stat.st_mtime_ns)
    except OSError:
        return None


def cache_valid():
    """Whether the cache file's header and payload shape are current."""
    try:
        if not 0 < SERVICES_PATH.stat().st_size <= MAX_BYTES:
            return False
        payload = json.loads(SERVICES_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError, UnicodeError):
        return False
    expected_hm_source = os.fspath(home_manager_source() or "")
    if not (
        isinstance(payload, dict)
        and payload.get("schema") == SCHEMA
        and str(payload.get("system") or "") == nix_catalog.linux_arch()
        and str(payload.get("hm_source") or "") == expected_hm_source
        and isinstance(payload.get("services"), dict)
    ):
        return False
    # Every discovery level must be present, even when it has no services.
    # Older caches that only evaluated the local install level must refresh so
    # system-only service packages can be recognised and refused/hidden on
    # non-NixOS hosts.
    present = {
        str(scope)
        for scope, entries in payload["services"].items()
        if isinstance(entries, dict)
    }
    return set(discovery_scopes()) <= present


def needs_refresh():
    if not enabled():
        return False
    if _path_state(SERVICES_PATH) is None:
        return True
    if not cache_valid():
        return True
    if not nix_catalog.valid_snapshot():
        return True
    return cache_older_than_snapshot()


def cache_older_than_snapshot():
    """Cheap mtime check that avoids validating the large package snapshot."""
    try:
        service_state = SERVICES_PATH.stat()
        if service_state.st_mtime < nix_catalog.RAW_PATH.stat().st_mtime:
            return True
        return time.time() - service_state.st_mtime >= nix_catalog.MAX_AGE
    except OSError:
        return True


