def _nix_string(value):
    text = json.dumps(str(value), ensure_ascii=False)
    # Double-quoted Nix strings interpolate ``${``; JSON escaping alone does
    # not protect it.
    return text.replace("${", "\\${")


def _render_value(kind, value):
    if kind == "bool":
        return "true" if value else "false"
    if kind == "int":
        return str(int(value))
    if kind == "float":
        return repr(float(value))
    if kind == "list":
        return "[ " + " ".join(_nix_string(item) for item in value) + " ]"
    return _nix_string(value)


def render_module(scope, state):
    """Render the service module text from a validated state mapping."""
    clean = _clean_state(state)
    payload = {
        name: {"options": dict(sorted(entry["options"].items()))}
        for name, entry in sorted(clean.items())
    }
    lines = [
        "{ lib, pkgs, ... }:" if scope == "system" else "{ pkgs, ... }:",
        "",
        _MODULE_HEADER,
        STATE_PREFIX
        + json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")),
        "{",
    ]
    for name, entry in sorted(clean.items()):
        lines.append(f"  services.{name} = {{")
        lines.append("    enable = true;")
        for path, value in entry["options"].items():
            kind = _infer_kind(value)
            if kind is None or value is None:
                continue
            lines.append(f"    {path} = {_render_value(kind, value)};")
        lines.append("  };")
    lines.extend(["}", ""])
    return "\n".join(lines)


