def _classify_type(description, type_name):
    """Resolve a NixOS option type to a supported widget kind and choices."""
    text = str(description or "").strip()
    name = str(type_name or "").strip()
    if text == "boolean" or name == "bool":
        return "bool", []
    if text.startswith("one of "):
        choices = re.findall(r'"((?:[^"\\]|\\.)*)"', text)
        if choices:
            return "enum", choices
        return None, []
    if text in ("string", "non-empty string", "single line string"):
        return "text", []
    if text in ("absolute path", "path", "path not in the Nix store"):
        return "text", []
    if text in (
        "signed integer",
        "unsigned integer",
        "positive integer, meaning >0",
        "16 bit unsigned integer; between 0 and 65535 (both inclusive)",
    ):
        return "int", []
    if text == "floating point number":
        return "float", []
    if text in ("list of string", "list of non-empty string", "list of absolute path"):
        return "list", []
    return None, []


def _clean_default(kind, value, choices):
    if value is None:
        return None
    if kind == "bool":
        return value if isinstance(value, bool) else None
    if kind == "enum":
        return value if isinstance(value, str) and value in choices else None
    if kind == "int":
        if isinstance(value, bool) or not isinstance(value, int):
            return None
        return value
    if kind == "float":
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            return None
        number = float(value)
        return number if math.isfinite(number) else None
    if kind == "text":
        return value if isinstance(value, str) else None
    if kind == "list":
        if not isinstance(value, list):
            return None
        return [str(item) for item in value if isinstance(item, str)]
    return None


def _clean_option(value):
    if not isinstance(value, dict):
        return None
    path = str(value.get("path") or "").strip()
    if not _PATH_RE.fullmatch(path):
        return None
    kind, choices = _classify_type(value.get("type"), value.get("typeName"))
    if kind is None:
        return None
    return {
        "path": path,
        "kind": kind,
        "type": str(value.get("type") or "").strip(),
        "description": str(value.get("description") or "").strip(),
        "default": _clean_default(kind, value.get("default"), choices),
        "choices": choices,
    }


def _clean_service(name, value):
    if not isinstance(value, dict) or not _ATTR_RE.fullmatch(str(name or "")):
        return None
    options = []
    seen = set()
    for item in value.get("options") or ():
        cleaned = _clean_option(item)
        if cleaned is None or cleaned["path"] in seen:
            continue
        seen.add(cleaned["path"])
        options.append(cleaned)
    options.sort(key=lambda item: item["path"])
    return {
        "name": name,
        "description": str(value.get("description") or "").strip(),
        "options": options,
    }


def _clean_services(raw):
    """Validate a scope -> service map from the discovery cache."""
    if not isinstance(raw, dict):
        return {}
    scoped = {}
    for scope in SERVICE_SCOPES:
        entries = raw.get(scope)
        if not isinstance(entries, dict):
            continue
        services = {}
        for name, value in entries.items():
            cleaned = _clean_service(str(name), value)
            if cleaned is not None:
                cleaned["scope"] = scope
                services[cleaned["name"]] = cleaned
        scoped[scope] = services
    return scoped


def _read_services(path):
    try:
        if not 0 < path.stat().st_size <= MAX_BYTES:
            return {}
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError, UnicodeError):
        return {}
    if not isinstance(payload, dict) or payload.get("schema") != SCHEMA:
        return {}
    if str(payload.get("system") or "") != nix_catalog.linux_arch():
        return {}
    return _clean_services(payload.get("services"))


def cache_available():
    """Whether a discovery cache file exists (even if it has no services)."""
    return _path_state(SERVICES_PATH) is not None


def cached_services():
    """Return the last discovery result as a scope -> service map."""
    if not nix_catalog.enabled():
        return {}
    key = _path_state(SERVICES_PATH)
    with _LOCK:
        if (
            key is not None
            and _CACHE["path"] == os.fspath(SERVICES_PATH)
            and _CACHE["mtime"] == key
        ):
            return {scope: dict(values) for scope, values in _CACHE["services"].items()}
        services = _read_services(SERVICES_PATH) if key else {}
        _CACHE["path"] = os.fspath(SERVICES_PATH)
        _CACHE["mtime"] = key
        _CACHE["services"] = services
        return {scope: dict(values) for scope, values in services.items()}


def cached_scope_services(scope):
    value = str(scope or "").strip()
    if value not in SERVICE_SCOPES:
        return {}
    return cached_services().get(value, {})


def service_capabilities(name):
    """Capabilities for one attribute across every available level."""
    value = str(name or "").strip()
    if not value:
        return {}
    services = cached_services()
    return {
        scope: services[scope][value]
        for scope in SERVICE_SCOPES
        if value in services.get(scope, {})
    }


def cached_service(name, scope=None):
    value = str(name or "").strip()
    if not value:
        return None
    requested = str(scope or "").strip()
    capabilities = service_capabilities(value)
    if not capabilities:
        return None
    if requested in capabilities:
        return capabilities[requested]
    for candidate in scopes():
        if candidate in capabilities:
            return capabilities[candidate]
    return next(iter(capabilities.values()))


def service_for_name(name, scope=None):
    """Resolve one service capability available on this host."""
    value = str(name or "").strip()
    if not value:
        return None
    requested = str(scope or "").strip()
    capabilities = service_capabilities(value)
    if not capabilities:
        return None
    available = scopes()
    if requested in available and requested in capabilities:
        return capabilities[requested]
    for candidate in available:
        if candidate in capabilities:
            return capabilities[candidate]
    # Never fall back to a capability whose level is unavailable on this host:
    # a NixOS-only service must not be presented as an installable service on
    # a Home Manager-only system.
    return None


def unavailable_service_attrs():
    """Service packages requiring a level this host cannot provide.

    On non-NixOS systems a package whose only service capability is a NixOS
    system module cannot be installed as a service. It is hidden from the
    catalog instead of being offered as a plain package that would not work.
    """
    if nix_catalog.is_nixos():
        return set()
    services = cached_services()
    home = set(services.get("home-manager") or ())
    system = set(services.get("system") or ())
    return system - home


def service_unavailable_on_host(attr):
    """Whether the attribute's only service levels are unavailable here."""
    value = str(attr or "").strip()
    if not value:
        return False
    capabilities = service_capabilities(value)
    if not capabilities:
        return False
    available = set(scopes())
    return not any(scope in available for scope in capabilities)


def service_for(info):
    """Resolve the service of one selected Nix source, if any."""
    if not isinstance(info, dict) or not enabled():
        return None
    name = str(info.get("nix_name") or info.get("package-name") or "").strip()
    if not name:
        return None
    return service_for_name(name, info.get("nix_scope"))


def is_service_attr(attr):
    value = str(attr or "").strip()
    return bool(value) and service_for_name(value) is not None


