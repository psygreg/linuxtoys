def _empty_value(kind):
    if kind == "bool":
        return False
    if kind == "int" or kind == "float":
        return None
    if kind == "list":
        return []
    if kind == "enum":
        return ""
    return ""


def _queued_service(service_name, scope="system"):
    try:
        from . import nix_queue

        records = [
            record
            for record in nix_queue.snapshot()
            if record.get("kind") == "service"
            and str(record.get("service") or record.get("attr") or "") == service_name
            and str(record.get("scope") or "") == scope
        ]
    except Exception:
        return None
    if not records:
        return None
    records.sort(key=lambda record: int(record.get("created") or 0))
    return records[-1]


def service_state(info, scope=None):
    """Return the install/queue state and effective option rows for a source."""
    service = service_for(info) if scope in (None, "") else service_for_name(
        (info or {}).get("nix_name") if isinstance(info, dict) else "", scope
    )
    if service is None:
        return None
    name = service["name"]
    actual_scope = str(service.get("scope") or scope or "system")
    pending = _queued_service(name, actual_scope)
    installed = name in installed_services(actual_scope)
    stored = read_state(module_path(actual_scope)).get(name, {}).get("options", {})
    queued_options = (pending or {}).get("options") if pending else None
    if not isinstance(queued_options, dict):
        queued_options = {}

    rows = []
    seen = set()
    pending_install = bool(
        pending is not None
        and str(pending.get("action") or "") == "install"
    )
    for option in service["options"]:
        path = option["path"]
        seen.add(path)
        saved = path in stored or path in queued_options
        if path in queued_options:
            value = queued_options[path]
        elif pending_install:
            # An install record replaces the stored override set on apply, so
            # options absent from it are back at their upstream default (or
            # empty for a default the evaluator could not resolve).
            value = (
                option["default"]
                if option["default"] is not None
                else _empty_value(option["kind"])
            )
        elif path in stored:
            value = stored[path]
        elif option["default"] is not None:
            value = option["default"]
        else:
            value = _empty_value(option["kind"])
        rows.append({**option, "value": value, "saved": saved})

    # Keep values recorded by an older nixpkgs revision visible and removable
    # instead of silently dropping them from the generated module.
    stale_source = {**stored, **queued_options}
    for path, value in sorted(stale_source.items()):
        if path in seen:
            continue
        kind = _infer_kind(value)
        if kind is None:
            continue
        rows.append(
            {
                "path": path,
                "kind": kind,
                "type": "",
                "description": "",
                "default": None,
                "choices": [],
                "value": value,
                "stale": True,
                "saved": True,
            }
        )

    action = str((pending or {}).get("action") or "")
    if pending is not None and action == "remove":
        status = "removing"
    elif pending is not None:
        status = "queued"
    elif installed:
        status = "installed"
    else:
        status = "available"
    return {
        "service": service,
        "name": name,
        "scope": actual_scope,
        "level": "user" if actual_scope == "home-manager" else "system",
        "status": status,
        "installed": installed,
        "pending": pending,
        "options": rows,
        "stored": stored,
    }


def clean_values(service, values):
    """Validate and normalize user-supplied option values for a service."""
    if not isinstance(service, dict):
        raise ValueError("Unknown Nix service")
    options = {
        option["path"]: option for option in service.get("options") or ()
    }
    cleaned = {}
    for path, value in (values or {}).items():
        path = str(path or "").strip()
        option = options.get(path)
        if option is None:
            raise ValueError(f"Unknown service option '{path}'")
        ok, normalized = _clean_option_value(
            option["kind"], value, option.get("choices") or []
        )
        if not ok:
            raise ValueError(
                f"Invalid value for service option '{path}' "
                f"({option['kind']})"
            )
        cleaned[path] = normalized
    return cleaned


def overrides_from_values(service, values):
    """Drop values equal to the current defaults (durable overrides)."""
    if not isinstance(service, dict):
        return {}
    defaults = {
        option["path"]: option["default"] for option in service.get("options") or ()
    }
    overrides = {}
    for path, value in clean_values(service, values).items():
        option = next(
            (
                item
                for item in service.get("options") or ()
                if item["path"] == path
            ),
            None,
        )
        if option is None:
            continue
        if option["default"] is not None and value == option["default"]:
            continue
        overrides[path] = value
    return overrides


