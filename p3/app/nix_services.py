"""Nix service discovery, option state and generated modules.

Some nixpkgs packages are only useful together with a service module.
Installing just ``pkgs.<name>`` leaves the daemon, udev rules or user/system
units undefined; the package must be enabled through ``services.<name>``
instead. LinuxToys therefore treats a catalog entry whose attribute has a
matching top-level service (with an ``enable`` boolean) as a service entry.

Two service levels are supported and discovered separately:

* **Home Manager** services are user-level by construction and work outside
  NixOS. They are rendered into the home ``linuxtoys-services.nix`` module.
* **NixOS** services are system-level and need the NixOS system
  configuration. They are rendered into ``linuxtoys-system-services.nix``.

The level is therefore the module source: Home Manager modules are user
services, NixOS modules are system services. A package present in both gains
both capabilities and the selected Nix source decides which one is used.

This module owns discovery of both option trees (cached like the package
snapshot), the durable selections stored as JSON comments in the generated
modules, rendering, and queued service application.

Only options with a safe, structured representation are offered: booleans,
enums, strings/paths, integers/floats and lists of strings. Packages,
submodules, free-form attrsets and functions stay out of the UI; the service
still installs with its own defaults. Unset direct service options always
resolve to the current nixpkgs/Home Manager default, so the app page reflects
the service's actual state even when the user never touched an option (nested
submodule defaults that cannot be forced safely stay empty until set).
"""

