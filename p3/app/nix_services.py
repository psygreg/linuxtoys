def _queue_operations(queue_path):
    try:
        payload = json.loads(Path(queue_path).read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError, UnicodeError):
        return []
    operations = payload.get("operations") if isinstance(payload, dict) else None
    return [item for item in operations or () if isinstance(item, dict)]


def _record_scope(record):
    scope = str(record.get("scope") or "").strip()
    return scope if scope in ("home-manager", "system") else ""


def _record_kind(record):
    return str(record.get("kind") or "package").strip() or "package"


def _record_created(record):
    try:
        return int(record.get("created") or 0)
    except (TypeError, ValueError):
        return 0


def _record_service(record):
    return str(record.get("service") or record.get("attr") or "").strip()


def _clean_queued_options(service, raw):
    if not isinstance(raw, dict):
        return {}
    options = {}
    for option in service.get("options") or ():
        path = option["path"]
        if path not in raw:
            continue
        ok, cleaned = _clean_option_value(
            option["kind"], raw[path], option.get("choices") or []
        )
        if ok:
            options[path] = cleaned
    return options


def apply_queue(scope, module, queue_path, output):
    """Apply this scope's queued service operations and render the module.

    Returns ``(state, changed, warnings)``. The caller publishes *output* only
    after a successful return, preserving the old module when rendering fails.
    """
    if scope not in SERVICE_SCOPES:
        raise ValueError("Invalid Nix service scope")
    state = read_state(module)
    operations = _queue_operations(queue_path)
    capability_map = cached_scope_services(scope) if enabled() else {}
    warnings = []
    changed = False

    service_ops = [
        record
        for record in operations
        if _record_kind(record) == "service" and _record_scope(record) == scope
    ]
    package_ops = [
        record
        for record in operations
        if _record_kind(record) == "package" and _record_scope(record) == scope
    ]
    if (
        any(
            str(record.get("action") or "").strip() == "install"
            for record in service_ops
        )
        and not capability_map
    ):
        raise ValueError(
            "Nix service metadata is unavailable; refresh the Nix category first"
        )

    service_ops.sort(
        key=lambda record: (_record_created(record), str(record.get("id") or ""))
    )
    for record in service_ops:
        name = _record_service(record)
        action = str(record.get("action") or "").strip()
        if not _ATTR_RE.fullmatch(name):
            warnings.append("Ignored a malformed Nix service operation.")
            continue
        if action == "install":
            current = capability_map.get(name)
            if current is None and name not in state:
                warnings.append(
                    f"Skipped service '{name}': it no longer exists in this "
                    "service revision."
                )
                continue
            if current is not None:
                options = _clean_queued_options(current, record.get("options"))
                entry = state.setdefault(name, {"options": {}})
                known = {option["path"] for option in current.get("options") or ()}
                # Preserve values recorded by an older nixpkgs revision so an
                # unrelated option save cannot silently drop them.
                preserved = {
                    path: value
                    for path, value in (entry.get("options") or {}).items()
                    if path not in known
                }
                entry["options"] = {**preserved, **options}
            elif "options" in record:
                entry = state.setdefault(name, {"options": {}})
                entry["options"] = _clean_state(
                    {name: {"options": record.get("options")}}
                ).get(name, {}).get("options", {})
            changed = True
        elif action == "remove":
            if state.pop(name, None) is not None:
                changed = True

    # A package operation for a service attribute is upgraded to the service
    # form. This covers operations queued before discovery finished and legacy
    # package selections, so a service is never installed as a bare package.
    for record in package_ops:
        name = str(record.get("attr") or "").strip()
        action = str(record.get("action") or "").strip()
        if not _ATTR_RE.fullmatch(name):
            continue
        if action == "remove":
            if state.pop(name, None) is not None:
                changed = True
        elif action == "install" and name in capability_map and name not in state:
            state[name] = {"options": {}}
            changed = True

    atomic_write_text(
        output, render_module(scope, state), mode=0o644, fsync=True
    )
    return state, changed, warnings


def remove_services(scope, module, names, output):
    """Drop entire service entries from the state and render."""
    if scope not in SERVICE_SCOPES:
        raise ValueError("Invalid Nix service scope")
    state = read_state(module)
    changed = False
    for name in names or ():
        name = str(name or "").strip()
        if name and name in state:
            state.pop(name, None)
            changed = True
    atomic_write_text(
        output, render_module(scope, state), mode=0o644, fsync=True
    )
    return changed


