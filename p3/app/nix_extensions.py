def _render_package_entry(host, entry):
    plugins = " ".join(entry["plugins"])
    plugin_list = f"with pkgs.{entry['set']}; [ {plugins} ]"
    if entry["mode"] == "apply":
        return f"    (pkgs.{entry['wrapper']} {{ {entry['arg']} = {plugin_list}; }})"
    return (
        f"    (pkgs.{entry['wrapper']}.override "
        f"{{ {entry['arg']} = {plugin_list}; }})"
    )


def render_module(scope, state):
    """Render the extension module text from a validated state mapping."""
    packages = "environment.systemPackages" if scope == "system" else "home.packages"
    clean = _clean_state(
        {
            host: {
                "set": entry.get("set"),
                "wrapper": entry.get("wrapper"),
                "mode": entry.get("mode"),
                "arg": entry.get("arg"),
                "plugins": list(entry.get("plugins") or ()),
            }
            for host, entry in state.items()
            if isinstance(entry, dict)
        }
    )
    payload = {
        host: {
            "set": entry["set"],
            "wrapper": entry["wrapper"],
            "mode": entry["mode"],
            "arg": entry["arg"],
            "plugins": entry["plugins"],
        }
        for host, entry in sorted(clean.items())
    }
    lines = [
        "{ pkgs, ... }:" if packages == "home.packages" else "{ lib, pkgs, ... }:",
        "",
        _MODULE_HEADER,
        STATE_PREFIX
        + json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")),
        "{",
        f"  {packages} = [",
    ]
    for host, entry in sorted(clean.items()):
        lines.append(_render_package_entry(host, entry))
    lines.extend(["  ];", "}", ""])
    return "\n".join(lines)


