def _nix_extensions_command(executable, system):
    return [
        executable,
        "--extra-experimental-features",
        "nix-command flakes",
        "eval",
        "--json",
        f"nixpkgs#legacyPackages.{system}",
        "--apply",
        _NIX_EXTENSIONS_EXPRESSION,
    ]


def load_or_refresh(force=False):
    """Refresh the extension discovery cache; returns its path or None.

    The previous valid cache is retained on any failure, so a transient Nix or
    network problem never removes the Extensions tabs.
    """
    global _LAST_FAILURE
    if not enabled():
        return None
    with _LOCK:
        if (
            not force
            and _LAST_FAILURE
            and time.time() - _LAST_FAILURE < FAILURE_BACKOFF
        ):
            return EXTENSIONS_PATH if cached_capabilities() else None
        if not force and not needs_refresh():
            return EXTENSIONS_PATH if cached_capabilities() else None
        executable = nix_catalog.nix_executable()
        system = nix_catalog.linux_arch()
        if not executable or not system:
            return None
        temporary = None
        try:
            nix_catalog.CACHE_DIR.mkdir(parents=True, exist_ok=True)
            fd, temporary = tempfile.mkstemp(
                dir=nix_catalog.CACHE_DIR, prefix="extensions-", suffix=".json"
            )
            environment = {
                **os.environ,
                "NIX_CONFIG": (
                    (os.environ.get("NIX_CONFIG", "") + "\n")
                    if os.environ.get("NIX_CONFIG")
                    else ""
                )
                + "extra-experimental-features = nix-command flakes\n",
                "LC_ALL": "C",
            }
            with os.fdopen(fd, "wb") as handle:
                result = subprocess.run(
                    _nix_extensions_command(executable, system),
                    stdout=handle,
                    stderr=subprocess.PIPE,
                    timeout=nix_catalog.SEARCH_TIMEOUT,
                    check=False,
                    env=environment,
                )
            if result.returncode:
                detail = result.stderr.decode("utf-8", "replace").strip().splitlines()
                raise RuntimeError(
                    detail[-1] if detail else "Nix extension evaluation failed"
                )
            size = os.path.getsize(temporary)
            if not 0 < size <= MAX_BYTES:
                raise ValueError("Nix extension metadata is empty or too large")
            raw = json.loads(Path(temporary).read_text(encoding="utf-8"))
            capabilities = _clean_capabilities(raw)
            if not capabilities:
                raise ValueError("Nix extension metadata contains no usable wrappers")
            if not enabled():
                return None
            # Publish the cache after the snapshot rewrite: the snapshot must
            # never look newer than the extension list it was filtered with,
            # or every readiness check would re-run discovery.
            try:
                nix_catalog.filter_extension_packages(capabilities)
            except Exception as error:
                logger.warning(
                    "Could not remove Nix extension packages from the catalog: %s",
                    error,
                )
            payload = {
                "schema": SCHEMA,
                "system": system,
                "updated": int(time.time()),
                "capabilities": capabilities,
            }
            atomic_write_text(
                os.fspath(EXTENSIONS_PATH),
                json.dumps(
                    payload,
                    ensure_ascii=False,
                    sort_keys=True,
                    separators=(",", ":"),
                )
                + "\n",
                mode=0o600,
                fsync=True,
            )
            with _LOCK:
                _CACHE["path"] = os.fspath(EXTENSIONS_PATH)
                _CACHE["mtime"] = _path_state(EXTENSIONS_PATH)
                _CACHE["capabilities"] = capabilities
            _LAST_FAILURE = 0.0
            return EXTENSIONS_PATH
        except Exception as error:
            _LAST_FAILURE = time.time()
            logger.warning(
                "Nix extension refresh failed; retaining cached data: %s", error
            )
            return EXTENSIONS_PATH if cached_capabilities() else None
        finally:
            if temporary:
                try:
                    os.unlink(temporary)
                except OSError:
                    pass


