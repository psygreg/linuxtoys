def import_name(scope):
    return (
        "linuxtoys-system-extensions.nix"
        if scope == "system"
        else "linuxtoys-extensions.nix"
    )


def module_path(scope):
    """Path of the generated extension module for one scope."""
    return Path(nix_catalog.module_path(scope)).parent / import_name(scope)


def empty_module(scope):
    packages = "environment.systemPackages" if scope == "system" else "home.packages"
    return (
        "{ pkgs, ... }:\n"
        "\n"
        f"{_MODULE_HEADER}\n"
        f"{STATE_PREFIX}{{}}\n"
        "{\n"
        f"  {packages} = [ ];\n"
        "}\n"
    )


def _read_module_text(path):
    try:
        return Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def read_state(path):
    """Read the extension selection recorded in a generated module."""
    for line in _read_module_text(path).splitlines():
        if not line.startswith(STATE_PREFIX):
            continue
        try:
            payload = json.loads(line[len(STATE_PREFIX):])
        except (ValueError, TypeError):
            return {}
        return _clean_state(payload)
    return {}


def _clean_state(payload):
    if not isinstance(payload, dict):
        return {}
    state = {}
    for host, value in payload.items():
        host = str(host or "").strip()
        if not _ATTR_RE.fullmatch(host):
            continue
        if isinstance(value, dict):
            plugins = value.get("plugins")
        elif isinstance(value, (list, tuple)):
            plugins = value
        else:
            plugins = None
        if not isinstance(plugins, (list, tuple)):
            continue
        clean = sorted(
            {
                str(attr).strip()
                for attr in plugins
                if _ATTR_RE.fullmatch(str(attr or "").strip())
            }
        )
        if not clean:
            continue
        metadata = value if isinstance(value, dict) else {}
        entry = {
            "set": str(metadata.get("set") or "").strip(),
            "wrapper": str(metadata.get("wrapper") or "").strip(),
            "mode": str(metadata.get("mode") or "").strip(),
            "arg": str(metadata.get("arg") or "").strip(),
            "plugins": clean,
        }
        if not (
            _ATTR_RE.fullmatch(entry["set"])
            and _ATTR_RE.fullmatch(entry["wrapper"])
            and _ATTR_RE.fullmatch(entry["arg"])
            and entry["mode"] in _VALID_MODES
        ):
            # Old or hand-written compact records cannot be rendered safely.
            continue
        state[host] = entry
    return state


def installed_plugins(host, scope=None):
    """Return the selected plugin attributes for one host."""
    host = str(host or "").strip()
    if not host:
        return set()
    scopes = [scope] if scope in ("home-manager", "system") else [
        "home-manager",
        "system",
    ]
    plugins = set()
    for item in scopes:
        state = read_state(module_path(item))
        entry = state.get(host)
        if entry:
            plugins.update(entry["plugins"])
    return plugins


def installed_extensions(info):
    """Return installed plugin attributes for the app page state."""
    if not isinstance(info, dict):
        return set()
    host = str(info.get("nix_name") or "").strip()
    scope = str(info.get("nix_scope") or "").strip()
    return installed_plugins(host, scope or None)


def installed_hosts(scope):
    """Hosts wrapped by the generated extension module for one scope."""
    return set(read_state(module_path(scope)))


