"""Nix package extensions (plugins/add-ons) discovery and state.

Some nixpkgs applications accept optional plugins through a dedicated wrapper
or an overridable ``*-with-plugins`` derivation. LinuxToys never installs those
plugin packages as standalone applications: a plugin only works when the host
package is wrapped with it. This module owns:

* discovery of the wrappers nixpkgs exposes (one ``nix eval`` whose result is
  cached like the package snapshot);
* the durable extension selection, stored as a JSON comment inside the
  generated ``linuxtoys-extensions.nix`` / ``linuxtoys-system-extensions.nix``
  module that the main LinuxToys module imports;
* rendering that module and applying queued extension operations.

The wrapper table is deliberately small and explicit. Plugin-set membership is
discovered from the live nixpkgs evaluation, but the way a host accepts plugins
must be known to be safe: nixpkgs has no uniform ``plugins`` argument, and
blindly probing wrappers would call arbitrary functions. Entries whose wrapper
or plugin set disappears are skipped by the next discovery pass; existing state
records the wrapper it was created with so it keeps rendering.

The generated state comment:

    # LinuxToys extensions state: {"obs-studio":{"plugins":[...],...}}

is machine-readable and inert for Nix evaluation. The module body contains the
wrapped package expressions built from that state.
"""

from __future__ import annotations

import json
import logging
import os
import re
import subprocess
import sys
import tempfile
import threading
import time
from pathlib import Path

from . import nix_catalog
from .atomic_io import atomic_write_text

EXTENSIONS_PATH = nix_catalog.CACHE_DIR / "extensions.json"
MAX_BYTES = 16 * 1024 * 1024
SCHEMA = 2
STATE_PREFIX = "# LinuxToys extensions state: "
_MODULE_HEADER = "# Generated by LinuxToys. Extensions selected for Nix packages are wrapped here."
_ATTR_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_'-]*$")
_VALID_MODES = ("apply", "override")
_LOCK = threading.RLock()
_CACHE = {"path": None, "mtime": None, "capabilities": {}}
_LAST_FAILURE = 0.0
FAILURE_BACKOFF = 60 * 60
logger = logging.getLogger(__name__)

# The evaluation receives the nixpkgs package set through ``--apply``.
# ``wrapperTable`` is the explicit safety boundary described in the module
# docstring; the rest (which plugin sets and members exist) is discovered.
_NIX_EXTENSIONS_EXPRESSION = r"""
pkgs:
let
  lib = pkgs.lib;
  # To support a new plugin host, verify that its wrapper accepts one of the
  # argument names below with a list of packages from the matching set, then
  # add it here. Discovery finds the set members; this table is the safety
  # boundary that guarantees the generated module is evaluable.
  wrapperTable = {
    "gimp-with-plugins" = "plugins";
    "gimp3-with-plugins" = "plugins";
    "deadbeef-with-plugins" = "plugins";
    "supercollider-with-plugins" = "plugins";
    "wayfire-with-plugins" = "plugins";
    "wrapOBS" = "plugins";
    "wrapFish" = "pluginPkgs";
  };
  aliases = {
    obs-studio = "wrapOBS";
    fish = "wrapFish";
  };
  isDerivation = value:
    builtins.isAttrs value && ((value.type or "") == "derivation");
  isCallable = value:
    builtins.isFunction value
    || (builtins.isAttrs value && builtins.hasAttr "__functor" value);
  pluginSetNames = builtins.filter
    (name:
      builtins.match ".*-plugins" name != null
      || builtins.match ".*Plugins" name != null)
    (builtins.attrNames pkgs);
  baseOf = name:
    let
      dashed = builtins.match "(.*)-plugins" name;
      camel = builtins.match "(.*)Plugins" name;
    in
    if dashed != null then builtins.head dashed
    else if camel != null then builtins.head camel
    else null;
  wrapperFor = base:
    let
      candidates = [ "${base}-with-plugins" "${base}-with-extensions" ]
        ++ (if builtins.hasAttr base aliases then [ aliases.${base} ] else [ ]);
      usable = builtins.filter
        (name: builtins.hasAttr name wrapperTable && builtins.hasAttr name pkgs)
        candidates;
    in
    if usable == [ ] then null else builtins.head usable;
  capabilityFor = setName:
    let
      base = baseOf setName;
      wrapper = if base == null then null else wrapperFor base;
      hostPname =
        if base != null && builtins.hasAttr base pkgs
        then (pkgs.${base}.pname or base)
        else base;
      wrapperVariants =
        if base == null then [ ]
        else builtins.filter
          (name: lib.hasPrefix "${base}-with-" name && isDerivation pkgs.${name})
          (builtins.attrNames pkgs);
      pluginRow = name:
        let
          evaluated = builtins.tryEval (
            let
              plugin = pkgs.${setName}.${name};
              meta = plugin.meta or { };
              problems = meta.problems or { };
            in
            if !(isDerivation plugin) then null
            else if (meta.broken or false) || ((problems.broken or false) != false)
              || !(meta.available or true) then null
            else {
              attr = name;
              pname = plugin.pname or name;
              version = plugin.version or "";
              description = meta.description or "";
            }
          );
        in
        if evaluated.success then evaluated.value else null;
      plugins = if base == null || wrapper == null || !(builtins.isAttrs pkgs.${setName}) then [ ] else builtins.filter
        (item: item != null && item.attr != base && item.pname != hostPname)
        (map pluginRow (builtins.attrNames pkgs.${setName}));
    in
    if base == null || wrapper == null || plugins == [ ] then null
    else {
      host = base;
      set = setName;
      inherit wrapper;
      arg = wrapperTable.${wrapper};
      mode = if isCallable pkgs.${wrapper} then "apply" else "override";
      wrappers = lib.unique ([ wrapper ] ++ wrapperVariants);
      inherit plugins;
    };
  capabilities = builtins.filter (item: item != null)
    (map
      (name:
        let evaluated = builtins.tryEval (capabilityFor name); in
        if evaluated.success then evaluated.value else null)
      pluginSetNames);
in
builtins.listToAttrs (map (item: { name = item.host; value = item; }) capabilities)
"""


def enabled():
    """Extensions are only meaningful while the Nix subsystem is usable."""
    return bool(nix_catalog.enabled())


def _path_state(path):
    try:
        stat = path.stat()
        return (stat.st_size, stat.st_mtime_ns)
    except OSError:
        return None


def needs_refresh():
    if not enabled():
        return False
    cached = cached_capabilities()
    if not cached:
        return True
    if not nix_catalog.valid_snapshot():
        # The package snapshot drives which hosts are offered; refresh with it.
        return True
    return cache_older_than_snapshot()


def cache_older_than_snapshot():
    """Cheap mtime check that avoids validating the large package snapshot."""
    try:
        extension_state = EXTENSIONS_PATH.stat()
        if extension_state.st_mtime < nix_catalog.RAW_PATH.stat().st_mtime:
            return True
        return time.time() - extension_state.st_mtime >= nix_catalog.MAX_AGE
    except OSError:
        return True


def _clean_capability(host, value):
    """Return a validated capability dict, or None for malformed entries."""
    if not isinstance(value, dict) or not _ATTR_RE.fullmatch(str(host or "")):
        return None
    set_attr = str(value.get("set") or "").strip()
    wrapper = str(value.get("wrapper") or "").strip()
    arg = str(value.get("arg") or "").strip()
    mode = str(value.get("mode") or "").strip()
    if not _ATTR_RE.fullmatch(set_attr) or not _ATTR_RE.fullmatch(wrapper):
        return None
    if not _ATTR_RE.fullmatch(arg) or mode not in _VALID_MODES:
        return None
    wrappers = []
    for item in value.get("wrappers") or ():
        name = str(item or "").strip()
        if _ATTR_RE.fullmatch(name) and name not in wrappers:
            wrappers.append(name)
    if wrapper not in wrappers:
        wrappers.insert(0, wrapper)
    plugins = []
    for item in value.get("plugins") or ():
        if not isinstance(item, dict):
            continue
        attr = str(item.get("attr") or "").strip()
        if not _ATTR_RE.fullmatch(attr) or attr == host:
            continue
        plugins.append(
            {
                "attr": attr,
                "pname": str(item.get("pname") or attr).strip() or attr,
                "version": str(item.get("version") or "").strip(),
                "description": str(item.get("description") or "").strip(),
            }
        )
    if not plugins:
        return None
    plugins.sort(key=lambda item: item["attr"])
    return {
        "host": host,
        "set": set_attr,
        "wrapper": wrapper,
        "mode": mode,
        "arg": arg,
        "wrappers": sorted(set(wrappers)),
        "plugins": plugins,
    }


def _clean_capabilities(raw):
    if not isinstance(raw, dict):
        return {}
    capabilities = {}
    for host, value in raw.items():
        cleaned = _clean_capability(str(host), value)
        if cleaned is not None:
            capabilities[cleaned["host"]] = cleaned
    return capabilities


def _read_capabilities(path):
    try:
        if not 0 < path.stat().st_size <= MAX_BYTES:
            return {}
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError, UnicodeError):
        return {}
    if not isinstance(payload, dict) or payload.get("schema") != SCHEMA:
        return {}
    if str(payload.get("system") or "") != nix_catalog.linux_arch():
        return {}
    return _clean_capabilities(payload.get("capabilities"))


def cached_capabilities():
    """Return the last discovery result, without ever running Nix."""
    if not enabled():
        return {}
    key = _path_state(EXTENSIONS_PATH)
    with _LOCK:
        if key is not None and _CACHE["path"] == os.fspath(EXTENSIONS_PATH) and _CACHE["mtime"] == key:
            return dict(_CACHE["capabilities"])
        capabilities = _read_capabilities(EXTENSIONS_PATH) if key else {}
        _CACHE["path"] = os.fspath(EXTENSIONS_PATH)
        _CACHE["mtime"] = key
        _CACHE["capabilities"] = capabilities
        return dict(capabilities)


def capability(info):
    """Resolve the extension capability of one selected Nix source, if any."""
    if not isinstance(info, dict):
        return None
    host = str(info.get("nix_name") or "").strip()
    if not host:
        return None
    return cached_capabilities().get(host)


def catalog_wrappers():
    """Wrapper attributes that must never appear as standalone catalog cards."""
    wrappers = set()
    for cap in cached_capabilities().values():
        wrappers.update(
            str(name).strip()
            for name in (cap.get("wrappers") or ())
            if str(name).strip()
        )
    return wrappers


def search_extensions(query):
    """Return ``(host_attr, score)`` matches for an extension name.

    Used by catalog search so typing a plugin name resolves to the host app
    whose Extensions tab contains it. Hyphens, underscores and whitespace are
    normalized so "background removal" also finds ``obs-backgroundremoval``.
    """
    target = str(query or "").strip().casefold()
    if len(target) < 2:
        return []

    def normalize(value):
        return re.sub(r"[-_\s]+", " ", str(value or "").casefold()).strip()

    target_normalized = normalize(target)
    matches = {}
    for cap in cached_capabilities().values():
        host = str(cap.get("host") or "").strip()
        if not host:
            continue
        for plugin in cap.get("plugins") or ():
            attr = str(plugin.get("attr") or "").casefold()
            pname = str(plugin.get("pname") or "").casefold()
            description = str(plugin.get("description") or "").casefold()
            attr_normalized = normalize(attr)
            pname_normalized = normalize(pname)
            description_normalized = normalize(description)
            attr_compact = attr_normalized.replace(" ", "")
            pname_compact = pname_normalized.replace(" ", "")
            target_compact = target_normalized.replace(" ", "")
            if attr == target or pname == target:
                score = 100
            elif attr_normalized == target_normalized or pname_normalized == target_normalized:
                score = 100
            elif attr.startswith(target) or attr_normalized.startswith(target_normalized):
                score = 85
            elif pname.startswith(target) or pname_normalized.startswith(target_normalized):
                score = 80
            elif target in attr or target_normalized in attr_normalized:
                score = 70
            elif target in pname or target_normalized in pname_normalized:
                score = 65
            elif target_compact and (
                target_compact in attr_compact or target_compact in pname_compact
            ):
                score = 60
            elif target in description or target_normalized in description_normalized:
                score = 30
            else:
                continue
            if score > matches.get(host, 0):
                matches[host] = score
    return sorted(matches.items(), key=lambda item: (-item[1], item[0]))


def extensions_for(info):
    """Return the extension rows for one selected Nix source.

    Discovered plugins come first. Installed plugins whose capability vanished
    after a nixpkgs update are still listed with a plain attribute name so the
    user can remove them instead of leaving an undeletable selection.
    """
    cap = capability(info)
    host = str((info or {}).get("nix_name") or "").strip()
    if not host:
        return []
    scope = str((info or {}).get("nix_scope") or "").strip()
    installed = installed_plugins(host, scope or None)
    result = []
    seen = set()
    if cap is not None:
        for plugin in cap["plugins"]:
            attr = plugin["attr"]
            seen.add(attr)
            result.append(
                _extension_item(host, plugin, cap, scope)
            )
    for attr in sorted(installed - seen):
        result.append(
            _extension_item(
                host,
                {"attr": attr, "pname": attr, "version": "", "description": ""},
                cap or {"set": "", "wrapper": "", "mode": "", "arg": ""},
                scope,
                stale=True,
            )
        )
    result.sort(key=lambda item: (item["stale"], item["name"].casefold(), item["nix_ext_attr"]))
    return result


def _extension_item(host, plugin, cap, scope, stale=False):
    attr = plugin["attr"]
    extension_id = f"nix-ext:{host}:{attr}"
    return {
        "id": extension_id,
        "nix_ext_id": extension_id,
        "nix_ext_host": host,
        "nix_ext_attr": attr,
        "nix_ext_set": str(cap.get("set") or ""),
        "nix_ext_scope": scope,
        "parent_id": host,
        "extension_kind": "nix",
        "name": str(plugin.get("pname") or attr),
        "summary": str(plugin.get("description") or ""),
        "version": str(plugin.get("version") or ""),
        "icon": "nix.svg",
        "stale": bool(stale),
    }


