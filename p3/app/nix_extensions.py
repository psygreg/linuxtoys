def _queue_operations(queue_path):
    try:
        payload = json.loads(Path(queue_path).read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError, UnicodeError):
        return []
    operations = payload.get("operations") if isinstance(payload, dict) else None
    return [item for item in operations or () if isinstance(item, dict)]


def _record_scope(record):
    scope = str(record.get("scope") or "").strip()
    return scope if scope in ("home-manager", "system") else ""


def _record_kind(record):
    return str(record.get("kind") or "package").strip() or "package"


def _record_created(record):
    try:
        return int(record.get("created") or 0)
    except (TypeError, ValueError):
        return 0


def _add_capability_state(state, capability_entry, plugin_attr):
    host = capability_entry["host"]
    if plugin_attr not in {item["attr"] for item in capability_entry["plugins"]}:
        return False
    entry = state.setdefault(
        host,
        {
            "set": capability_entry["set"],
            "wrapper": capability_entry["wrapper"],
            "mode": capability_entry["mode"],
            "arg": capability_entry["arg"],
            "plugins": [],
        },
    )
    # Refresh the mechanism from the current discovery pass while keeping the
    # already selected plugins.
    entry.update(
        {
            "set": capability_entry["set"],
            "wrapper": capability_entry["wrapper"],
            "mode": capability_entry["mode"],
            "arg": capability_entry["arg"],
        }
    )
    if plugin_attr in entry["plugins"]:
        return False
    entry["plugins"] = sorted({*entry["plugins"], plugin_attr})
    return True


def apply_queue(scope, module, queue_path, output):
    """Apply this scope's queued extension operations and render the module.

    Returns ``(state, changed, warnings)``. The caller publishes *output* only
    after a successful return, preserving the old module when rendering fails.
    """
    if scope not in ("home-manager", "system"):
        raise ValueError("Invalid Nix extension scope")
    state = read_state(module)
    operations = _queue_operations(queue_path)
    capability_map = cached_capabilities() if enabled() else {}
    warnings = []
    changed = False

    extension_ops = [
        record
        for record in operations
        if _record_kind(record) == "extension" and _record_scope(record) == scope
    ]
    if extension_ops and not capability_map:
        raise ValueError(
            "Nix extension metadata is unavailable; refresh the Nix category first"
        )

    extension_ops.sort(
        key=lambda record: (
            _record_created(record),
            str(record.get("id") or ""),
        )
    )
    for record in extension_ops:
        host = str(record.get("host") or "").strip()
        plugin_attr = str(record.get("extension") or "").strip()
        action = str(record.get("action") or "").strip()
        if not _ATTR_RE.fullmatch(host) or not _ATTR_RE.fullmatch(plugin_attr):
            warnings.append("Ignored a malformed Nix extension operation.")
            continue
        if action == "install":
            current = capability_map.get(host)
            if current is None:
                warnings.append(
                    f"Skipped '{plugin_attr}': '{host}' no longer accepts extensions "
                    "in this nixpkgs revision."
                )
                continue
            if _add_capability_state(state, current, plugin_attr):
                changed = True
        elif action == "remove":
            entry = state.get(host)
            if entry is None or plugin_attr not in entry["plugins"]:
                continue
            entry["plugins"] = [attr for attr in entry["plugins"] if attr != plugin_attr]
            if not entry["plugins"]:
                state.pop(host, None)
            changed = True

    # Removing the host package always drops its extensions, even when the
    # extension queue holds a plugin install for the same apply.
    for record in operations:
        if _record_kind(record) != "package":
            continue
        if _record_scope(record) != scope:
            continue
        if str(record.get("action") or "").strip() != "remove":
            continue
        host = str(record.get("attr") or "").strip()
        if host and host in state:
            state.pop(host, None)
            changed = True

    atomic_write_text(output, render_module(scope, state), mode=0o644, fsync=True)
    return state, changed, warnings


def remove_hosts(scope, module, hosts, output):
    """Drop entire host entries from the extension state and render."""
    if scope not in ("home-manager", "system"):
        raise ValueError("Invalid Nix extension scope")
    state = read_state(module)
    changed = False
    for host in hosts or ():
        host = str(host or "").strip()
        if host and host in state:
            state.pop(host, None)
            changed = True
    atomic_write_text(output, render_module(scope, state), mode=0o644, fsync=True)
    return changed


