#!/bin/bash
# name: OpenRGB
# version: 1.0
# description: oprgb_desc
# icon: openrgb.svg
# repo: https://openrgb.org
# compat: !steamos

# --- Start of the script code ---
source "$SCRIPT_DIR/libs/helpers.lib"
_lang_

find_openrgb_appimage() {
    find "$HOME/AppImages" -maxdepth 1 -type f -iname '*openrgb*.appimage' \
        -printf '%T@ %p\n' 2>/dev/null | sort -rn | head -n1 | cut -d' ' -f2-
}

generate_openrgb_rules() {
    local APPIMAGE_PATH
    APPIMAGE_PATH=$(find_openrgb_appimage)
    [[ -n "$APPIMAGE_PATH" ]] || fatal "OpenRGB AppImage not found in $HOME/AppImages"
    # Since OpenRGB 1.0 the udev rules are generated by OpenRGB itself
    # (https://openrgb.org/udev.html); --print-udev-rules writes them to stdout
    # and exits, so no privilege escalation is needed here.
    "$APPIMAGE_PATH" --print-udev-rules > 60-openrgb.rules
    [[ -s 60-openrgb.rules ]] || fatal "Failed to generate OpenRGB udev rules"
}

pkg_fromrelease https://github.com/CalcProgrammer1/OpenRGB
if is_fedora || is_ostree || is_rhel; then
    askpass
    rpmfusion_chk
    pkg_install openrgb-udev-rules
else
    generate_openrgb_rules
    askpass
    prep_create /etc/udev/rules.d/60-openrgb.rules
    copy_ -f 60-openrgb.rules /etc/udev/rules.d/
    # Remove the rules left in the old location by previous installers, or
    # OpenRGB warns that conflicting rules are installed twice.
    [ -f /usr/lib/udev/rules.d/60-openrgb.rules ] && prep_rm /usr/lib/udev/rules.d/60-openrgb.rules
    sudo udevadm control --reload-rules && sudo udevadm trigger
fi
info "$msg036"